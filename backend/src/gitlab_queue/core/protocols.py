from __future__ import annotations

from typing import TYPE_CHECKING, Any, Protocol, runtime_checkable

if TYPE_CHECKING:
    from asyncio import Lock
    from datetime import datetime

    from gitlab_queue.models.completion import CompletionRequest
    from gitlab_queue.models.mr import MergeRequest, Note
    from gitlab_queue.models.pipeline import Job, Pipeline
    from gitlab_queue.models.queue_item import QueueItem


@runtime_checkable
class GitLabClientProtocol(Protocol):
    async def get_mr(self, iid: int, *, include_diverged_commits_count: bool = False) -> MergeRequest: ...
    async def list_mrs_with_label(self, label: str, *, state: str = "opened") -> list[MergeRequest]: ...
    async def rebase_mr(self, iid: int) -> bool: ...
    async def check_rebase_status(self, iid: int) -> tuple[bool, bool, str | None]: ...
    async def get_mr_conflicts(self, iid: int) -> list[str]: ...
    async def merge_mr(self, iid: int, *, expected_sha: str | None = None) -> MergeRequest: ...
    async def remove_mr_label(self, iid: int, label: str) -> MergeRequest: ...

    async def get_mr_pipelines(self, iid: int) -> list[Pipeline]: ...
    async def get_latest_mr_pipeline(self, iid: int) -> Pipeline | None: ...
    async def get_pipeline_status(self, pipeline_id: int) -> Pipeline: ...
    async def retry_pipeline_job(self, job_id: int) -> Job: ...
    async def create_pipeline(self, ref: str) -> Pipeline: ...
    async def retry_pipeline(self, pipeline_id: int) -> Pipeline: ...
    async def cancel_pipeline(self, pipeline_id: int) -> Pipeline: ...
    async def get_pipeline_jobs(self, pipeline_id: int) -> list[Job]: ...

    async def add_comment(self, iid: int, body: str) -> Note: ...
    async def update_comment(self, iid: int, note_id: int, body: str) -> Note: ...
    async def add_or_update_pinned_comment(self, iid: int, body: str) -> Note: ...

    async def get_project_web_url(self) -> str: ...


@runtime_checkable
class QueueManagerProtocol(Protocol):
    def metadata_lock(self, project_id: int) -> Lock: ...
    def notification_lock(self, project_id: int, mr_iid: int) -> Lock: ...
    def admission_lock(self, project_id: int, mr_iid: int) -> Lock: ...
    def completion_lock(self, project_id: int, mr_iid: int) -> Lock: ...
    async def prepare_completion(
        self, project_id: int, mr_iid: int, request: CompletionRequest
    ) -> QueueItem | None: ...
    async def get_pending_completions(self, project_id: int) -> list[QueueItem]: ...
    async def save_completion_progress(self, project_id: int, queue_id: int, payload: dict[str, Any]) -> None: ...
    async def finalize_completion(self, project_id: int, item: QueueItem, payload: dict[str, Any]) -> bool: ...
    async def defer_requeue(
        self, project_id: int, item: QueueItem, request: dict[str, Any], *, allow_active: bool = False
    ) -> bool: ...
    async def cancel_requeue(
        self,
        project_id: int,
        queue_id: int,
        event_at: datetime,
        *,
        precision_us: int = 1,
        message_id: str | None = None,
        allow_active: bool = False,
    ) -> bool: ...
    async def stage_completion_positions(self, project_id: int, positions: dict[int, int], old_total: int) -> None: ...
    async def clear_pending_notification(self, project_id: int, mr_iid: int, pending: str) -> None: ...
    async def add_to_queue(self, project_id: int, mr: MergeRequest, is_hotfix: bool = False) -> Any: ...
    async def remove_from_queue(self, project_id: int, mr_iid: int) -> bool: ...
    async def get_queue_position(self, project_id: int, mr_iid: int) -> int | None: ...
    async def get_next_mr(self, project_id: int) -> Any | None: ...
    async def get_queue_item(self, project_id: int, mr_iid: int) -> Any | None: ...
    async def get_active_queue(self, project_id: int | None = None) -> list[Any]: ...
    async def get_queue_length(self, project_id: int | None = None) -> int: ...
    async def get_mr_state(self, project_id: int, mr_iid: int) -> dict[str, Any] | None: ...
    async def update_mr_state(self, project_id: int, mr_iid: int, state: str, **extra: Any) -> bool: ...
    async def update_hotfix_status(
        self,
        project_id: int,
        mr_iid: int,
        is_hotfix: bool,
        labels: list[str],
        *,
        expected_revision: tuple[int, int] | None = None,
        notify_positions: bool = False,
        admission_key: str | None = None,
    ) -> bool: ...
    async def complete_mr(
        self,
        project_id: int,
        mr_iid: int,
        status: str,
        failure_reason: str | None = None,
        pipeline_duration_seconds: int | None = None,
        pipeline_failed_jobs: list[str] | None = None,
        *,
        expected_queue_id: int | None = None,
    ) -> bool: ...
    async def get_queue_stats(self, project_id: int | None = None) -> dict[str, int]: ...
    async def get_stale_mrs(self, project_id: int, hours: int) -> list[Any]: ...
    async def mark_stale_warning_sent(self, project_id: int, mr_iid: int) -> bool: ...


@runtime_checkable
class NotifierProtocol(Protocol):
    async def completion_actor(self) -> dict[str, Any]: ...
    async def notify(self, mr_iid: int, status: str, **context: Any) -> Note | None: ...
    async def build_pipeline_url(self, pipeline_id: int) -> str: ...
    async def remove_queue_label(
        self, mr_iid: int, *, strict: bool = False, operation_id: str | None = None
    ) -> datetime | None: ...
    async def restore_queue_labels(
        self, mr_iid: int, labels: list[str], *, operation_id: str | None = None
    ) -> datetime | None: ...


@runtime_checkable
class StateMachineProtocol(Protocol):
    @property
    def current_state(self) -> Any: ...

    async def trigger_start_processing(self) -> None: ...
    async def trigger_rebase_complete(
        self,
        *,
        pipeline_id: int,
        pipeline_url: str,
        expected_sha: str | None = None,
    ) -> None: ...
    async def trigger_rebase_failed(self, *, conflicted_files: list[str], error_message: str) -> None: ...
    async def trigger_conflict_during_testing(self, *, conflicted_files: list[str], error_message: str) -> None: ...
    async def trigger_pipeline_success(self) -> None: ...
    async def trigger_pipeline_failed(
        self, *, failed_jobs: list[str], retried_jobs: dict[str, int], error_message: str
    ) -> None: ...
    async def trigger_merge_success(self) -> None: ...
    async def trigger_merge_failed(self, *, error_message: str) -> None: ...
    async def trigger_reset_to_queued(self, *, error_message: str) -> None: ...
    async def trigger_mark_removed(self, *, reason: str = "label_removed") -> None: ...
    async def trigger_timeout(self, *, max_wait_hours: int = 2) -> None: ...

    async def notify_job_retry(
        self,
        *,
        pipeline_id: int,
        pipeline_url: str | None,
        retried_jobs: list[str],
        retried_counts: dict[str, int],
        max_retries: int,
    ) -> None: ...
    async def notify_position_changed(self, *, old_position: int) -> None: ...
    async def notify_rebase_complete(self) -> None: ...
    async def notify_stale_warning(self, *, warning_hours: int) -> None: ...
    async def notify_rebase_during_testing(
        self,
        *,
        old_pipeline_id: int | None,
        new_pipeline_id: int,
        rebase_count: int,
        max_attempts: int,
        expected_sha: str | None = None,
    ) -> None: ...


class StateMachineFactoryProtocol(Protocol):
    async def __call__(
        self,
        project_id: int,
        mr_iid: int,
        notifier: NotifierProtocol,
        queue_manager: QueueManagerProtocol,
        *,
        target_branch: str = "master",
        websocket_manager: Any | None = None,
        position_notifier: Any | None = None,
    ) -> StateMachineProtocol: ...
