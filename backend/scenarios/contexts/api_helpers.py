def created_test_jwt(
    settings: MagicMock,
    *,
    user_id: int | None = None,
    username: str | None = None,
    name: str | None = None,
    email: str | None = None,
    avatar_url: str | None = None,
    project_id: int | None = None,
    expires_delta: timedelta | None = None,
) -> str:
    """Create a valid JWT token for testing.

    Uses d42 schemas to generate realistic random data for user fields.

    Args:
        settings: Mock settings with jwt_secret.
        user_id: GitLab user ID (generated if not provided).
        username: GitLab username (generated if not provided).
        name: User display name (generated if not provided).
        email: User email (generated if not provided).
        avatar_url: URL to user avatar (generated if not provided).
        project_id: GitLab project ID (defaults to settings.gitlab_project_id).
        expires_delta: Token expiration time (defaults to settings.jwt_expiration_hours).

    Returns:
        str: Encoded JWT token.
    """
    # Generate user data using d42 schema
    author_data = fake(AuthorSchema)

    actual_user_id = user_id if user_id is not None else author_data["id"]
    actual_username = username if username is not None else author_data["username"]
    actual_name = name if name is not None else author_data["name"]
    actual_email = email if email is not None else f"{actual_username}@example.com"
    actual_avatar_url = avatar_url if avatar_url is not None else author_data.get("avatar_url")

    now = datetime.now(UTC)

    if expires_delta is None:
        expires_delta = timedelta(hours=settings.jwt_expiration_hours)

    expire = now + expires_delta

    payload: dict[str, Any] = {
        "sub": str(actual_user_id),
        "username": actual_username,
        "name": actual_name,
        "email": actual_email,
        "avatar_url": actual_avatar_url,
        "project_id": project_id or settings.gitlab_project_id,
        "exp": expire,
        "iat": now,
    }

    token = jwt.encode(
        payload,
        settings.jwt_secret.get_secret_value(),
        algorithm="HS256",
    )
    assert token, "JWT token should be created"
    return token


