def created_test_queue_item(
    *,
    mr_iid: int | None = None,
    title: str | None = None,
    author_name: str | None = None,
    author_username: str | None = None,
    author_avatar: str | None = None,
    state: str = QueueState.QUEUED,
    is_hotfix: bool = False,
    labels: list[str] | None = None,
    target_branch: str | None = None,
    queued_at: datetime | None = None,
    started_at: datetime | None = None,
    finished_at: datetime | None = None,
    pipeline_id: int | None = None,
    pipeline_status: str | None = None,
    last_error: str | None = None,
    retry_count: int = 0,
) -> QueueItem:
    """Create a test QueueItem.

    Uses d42 schemas to generate realistic random data for required fields.
    Specific fields can be overridden via parameters.

    Args:
        mr_iid: MR internal ID (generated if not provided).
        title: MR title (generated if not provided).
        author_name: Author display name (generated if not provided).
        author_username: Author username (generated if not provided).
        author_avatar: Author avatar URL (generated if not provided).
        state: MR state (queued, rebasing, testing, merging, merged, failed).
        is_hotfix: Whether this is a hotfix.
        labels: MR labels.
        target_branch: Target branch (generated if not provided).
        queued_at: Queue timestamp.
        started_at: Processing start timestamp.
        finished_at: Finish timestamp.
        pipeline_id: Pipeline ID.
        pipeline_status: Pipeline status.
        last_error: Last error message.
        retry_count: Retry count.

    Returns:
        QueueItem: Test queue item with all fields configured.
    """
    # Generate base data using d42 schema
    item_data = fake(QueueItemSchema % {"state": state})

    actual_mr_iid = mr_iid if mr_iid is not None else item_data["mr_iid"]
    actual_title = title if title is not None else item_data["title"]
    actual_author_name = author_name if author_name is not None else item_data["author_name"]
    actual_author_username = author_username if author_username is not None else item_data["author_username"]
    actual_target_branch = target_branch if target_branch is not None else item_data["target_branch"]
    # Use generated avatar_url if available in schema, otherwise use provided or None
    actual_author_avatar = author_avatar if author_avatar is not None else item_data.get("author_avatar")

    item = QueueItem(
        mr_iid=actual_mr_iid,
        title=actual_title,
        author_name=actual_author_name,
        author_username=actual_author_username,
        author_avatar=actual_author_avatar,
        state=state,
        is_hotfix=is_hotfix,
        labels=labels or [Labels.MERGE_QUEUE],
        target_branch=actual_target_branch,
        queued_at=queued_at or datetime.now(UTC),
        started_at=started_at,
        finished_at=finished_at,
        pipeline_id=pipeline_id,
        pipeline_status=pipeline_status,
        last_error=last_error,
        retry_count=retry_count,
    )
    assert item.mr_iid == actual_mr_iid, "Queue item should have correct mr_iid"
    return item


