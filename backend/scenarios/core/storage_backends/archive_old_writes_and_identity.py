@scenario([params("CURRENT_TIMESTAMP"), params("not-a-timestamp")])
async def old_runtime_new_literal_writes_restore_raw_without_fabricating_due_or_retention(invalid_due):
    async with isolated_database_url() as url:
        with given("archived unknown dates and fresh old-runtime writes using literal server defaults"):
            await run_migrations(url)
            await seed_retry(url)
            await seed_dead(url)
            original_retry, original_dead = (
                await raw_rows(url, "webhook_retry_queue"),
                await raw_rows(url, "webhook_dlq"),
            )
            await asyncio.to_thread(command.downgrade, _get_alembic_config(url), "f6a7b8c9d0e1")
            async with Database(url) as database, database.transaction() as session:
                new_retry = (
                    await session.execute(
                        text(
                            "INSERT INTO webhook_retry_queue (project_id, event_type, payload, attempt_count, max_attempts, next_attempt_at, last_error) VALUES (123, 'merge_request', :payload, 2, 9, '2000-01-01T00:00:00Z', 'old write') RETURNING id"
                        ),
                        {"payload": PAYLOAD},
                    )
                ).scalar_one()
                new_dead = (
                    await session.execute(
                        text(
                            "INSERT INTO webhook_dlq (project_id, event_type, payload, attempt_count, last_error, original_created_at) VALUES (123, 'merge_request', :payload, 9, 'old failure', '2000-01-01 00:00:00') RETURNING id"
                        ),
                        {"payload": PAYLOAD},
                    )
                ).scalar_one()
            await seed_retry(url, entry_id=new_retry + 20, created_at="2000-01-01 00:00:00", due=invalid_due)
            old_retry, old_dead = await raw_rows(url, "webhook_retry_queue"), await raw_rows(url, "webhook_dlq")
            assert old_retry[0]["created_at"] == old_dead[0]["moved_to_dlq_at"] == "CURRENT_TIMESTAMP"

        with when("startup captures new incompatible writes before repairs and restores after the schema change"):
            await run_migrations(url)
            restored_retry, restored_dead = (
                await raw_rows(url, "webhook_retry_queue"),
                await raw_rows(url, "webhook_dlq"),
            )
            async with Database(url) as database:
                manager = WebhookRetryManager(database, clock=lambda: datetime(2050, 1, 1, tzinfo=UTC))
                ready = await manager.get_events_ready_for_retry(project_id=123)
                async with authenticated_dlq_client(database, manager) as client:
                    listing = await client.get("/api/dlq")
                    detail = await client.get(f"/api/dlq/{new_dead}")
                stats = await manager.get_dlq_stats(123)
                cleaned = await manager.cleanup_old_dlq_entries(days=1)
                unknown_move = await manager.get_dlq_entry(new_dead, 123)
            remaining_raw = await raw_rows(url, "webhook_dlq")

        with then("known due dates stay actionable while unknown due and age stay unknown without blocking other rows"):
            assert new_retry > original_retry[0]["id"]
            assert new_dead > original_dead[0]["id"]
            assert restored_retry == sorted(original_retry + old_retry, key=lambda row: row["id"])
            assert restored_dead == sorted(original_dead + old_dead, key=lambda row: row["id"])
            assert [item.id for item in ready] == [7, new_retry]
            assert all(item.created_at is None for item in ready)
            assert listing.status_code == detail.status_code == 200
            assert detail.json()["moved_to_dlq_at"] is None
            assert stats.total_count == 2
            assert cleaned == 1
            assert unknown_move.moved_to_dlq_at is None
            assert remaining_raw[0]["moved_to_dlq_at"] == "CURRENT_TIMESTAMP"


@scenario()
async def archived_and_deleted_sequence_high_water_survives_old_writes_and_repeated_cycles():
    async with isolated_database_url() as url:
        with given("unknown sources and deleted highest generated IDs in both retry tables"):
            await run_migrations(url)
            async with Database(url) as database:
                manager = WebhookRetryManager(database, max_attempts=1, base_delay_seconds=0)
                to_dead = await manager.add_to_retry_queue("merge_request", {}, "first", 123)
                await manager.mark_retry_failed(to_dead, "final", 123)
                dead_id = (await manager.get_dlq_entries(project_id=123))[0].id
                retry_id = await manager.add_to_retry_queue("merge_request", {}, "unknown", 123)
                retry_deleted = await manager.add_to_retry_queue("merge_request", {}, "deleted", 123)
                await manager.mark_retry_success(retry_deleted, 123)
                retry_high = await manager.add_to_retry_queue("merge_request", {}, "to deleted dead", 123)
                await manager.mark_retry_failed(retry_high, "final", 123)
                dead_high = max(item.id for item in await manager.get_dlq_entries(project_id=123))
                await manager.delete_dlq_entry(dead_high, 123)
                async with database.transaction() as session:
                    await session.execute(
                        text("UPDATE webhook_retry_queue SET created_at = NULL WHERE id = :id"), {"id": retry_id}
                    )
                    await session.execute(
                        text("UPDATE webhook_dlq SET original_created_at = NULL WHERE id = :id"), {"id": dead_id}
                    )
            originals = [await raw_rows(url, table) for table in ("webhook_retry_queue", "webhook_dlq")]

        with when("old-compatible writes and three downgrade/upgrade cycles share the original identities"):
            config = _get_alembic_config(url)
            await asyncio.to_thread(command.downgrade, config, "f6a7b8c9d0e1")
            async with Database(url) as database, database.transaction() as session:
                next_retry = (
                    await session.execute(
                        text(
                            "INSERT INTO webhook_retry_queue (project_id,event_type,payload,attempt_count,max_attempts,next_attempt_at,created_at) VALUES (456,'merge_request','{}',0,3,'2000-01-01 00:00:00','2000-01-01 00:00:00') RETURNING id"
                        )
                    )
                ).scalar_one()
                next_dead = (
                    await session.execute(
                        text(
                            "INSERT INTO webhook_dlq (project_id,event_type,payload,attempt_count,last_error,original_created_at,moved_to_dlq_at) VALUES (456,'merge_request','{}',3,'known','2000-01-01 00:00:00','2000-01-01 00:00:00') RETURNING id"
                        )
                    )
                ).scalar_one()
            await run_migrations(url)
            expected = [await raw_rows(url, table) for table in ("webhook_retry_queue", "webhook_dlq")]
            for _ in range(2):
                await asyncio.to_thread(command.downgrade, config, "f6a7b8c9d0e1")
                await run_migrations(url)
                assert [await raw_rows(url, table) for table in ("webhook_retry_queue", "webhook_dlq")] == expected
            await asyncio.to_thread(command.check, config)
            async with Database(url) as database, database.session() as session:
                pending = [
                    (
                        await session.execute(
                            text(f"SELECT COUNT(*) FROM {table} WHERE archive_id != '__contract_v1__'")
                        )
                    ).scalar_one()
                    for table in ARCHIVES
                ]
                owner = (
                    await session.execute(
                        text(
                            "SELECT owner, format_version FROM gq_retry_rollback_manifest_v1 WHERE archive_id = '__contract_v1__'"
                        )
                    )
                ).one()
                await session.commit()

        with then("neither deleted nor archived IDs are reused and the archive is ACKed only after exact restoration"):
            assert next_retry > retry_high > retry_deleted > retry_id
            assert next_dead > dead_high > dead_id
            assert expected[0][0] == originals[0][0]
            assert expected[1][0] == originals[1][0]
            assert pending == [0, 0, 0]
            assert tuple(owner) == ("gitlab_queue.retry_rollback", 1)


@scenario()
async def rollback_archive_survives_base_and_autogenerate_excludes_only_its_exact_tables():
    async with isolated_database_url() as url:
        with given("unknown retry/DLQ rows and compatible data outside the bounded archive guarantee"):
            await run_migrations(url)
            await seed_retry(url)
            await seed_dead(url)
            await seed_retry(url, entry_id=8, project_id=456, created_at="2000-01-01 00:00:00")
            archived_retry = (await raw_rows(url, "webhook_retry_queue"))[0]
            archived_dead = (await raw_rows(url, "webhook_dlq"))[0]
            config = _get_alembic_config(url)

        with when("full reversal drops managed tables while preserving archive storage, then upgrade restores it"):
            await asyncio.to_thread(command.downgrade, config, "base")
            async with Database(url) as database, database.engine.connect() as connection:
                tables_at_base = await connection.run_sync(lambda sync: inspect(sync).get_table_names())
            await run_migrations(url)
            retry = await raw_rows(url, "webhook_retry_queue")
            dead = await raw_rows(url, "webhook_dlq")
            await asyncio.to_thread(command.check, config)
            async with Database(url) as database, database.transaction() as session:
                await session.execute(text("CREATE TABLE unrelated_table_must_not_be_ignored (id INTEGER PRIMARY KEY)"))
            with catched(AutogenerateDiffsDetected) as unrelated:
                await asyncio.to_thread(command.check, config)

        with then(
            "only archived events survive base; compatible managed rows are intentionally outside this guarantee"
        ):
            assert set(tables_at_base) == {"alembic_version", *ARCHIVES}
            assert retry == [archived_retry]
            assert dead == [archived_dead]
            assert unrelated.type is AutogenerateDiffsDetected
            assert "unrelated_table_must_not_be_ignored" in str(unrelated.value)


@scenario()
async def nonportable_postgres_dates_do_not_block_valid_retry_or_expire_unknown_dlq_age():
    async with isolated_database_url() as url:
        with given("a valid due event mixed with relative, reserved, infinite, incomplete and normalized date strings"):
            await run_migrations(url)
            await seed_retry(url)
            await seed_dead(url)
            values = (
                "now",
                "today",
                "epoch",
                "infinity",
                "-infinity",
                "2026",
                "2000-01-01 BC",
                "2000-01-01 24:00:00",
                "2000-01-01 12:00:60",
            )
            for entry_id, value in enumerate(values, 20):
                await seed_retry(url, entry_id=entry_id, created_at="2000-01-01 00:00:00", due=value)
                await seed_dead(url, entry_id=entry_id, original=value, moved=value)
            before_retry = await raw_rows(url, "webhook_retry_queue")
            before_dead = await raw_rows(url, "webhook_dlq")

        with when("the raw corpus crosses downgrade/upgrade and real ready, API, stats and cleanup paths read it"):
            await asyncio.to_thread(command.downgrade, _get_alembic_config(url), "f6a7b8c9d0e1")
            await run_migrations(url)
            restored_retry = await raw_rows(url, "webhook_retry_queue")
            restored_dead = await raw_rows(url, "webhook_dlq")
            async with Database(url) as database:
                manager = WebhookRetryManager(database, clock=lambda: datetime(2050, 1, 1, tzinfo=UTC))
                ready = await manager.get_events_ready_for_retry(project_id=123)
                stats = await manager.get_dlq_stats(project_id=123)
                async with authenticated_dlq_client(database, manager) as client:
                    listing = await client.get("/api/dlq")
                cleaned = await manager.cleanup_old_dlq_entries(days=1)
            remaining = await raw_rows(url, "webhook_dlq")

        with then("only portable known instants affect scheduling or retention and every unknown raw value survives"):
            assert restored_retry == before_retry
            assert restored_dead == before_dead
            assert [item.id for item in ready] == [7]
            assert ready[0].created_at is None
            assert stats.total_count == len(values) + 1
            assert stats.oldest_entry == datetime.fromisoformat("2026-10-16T23:15:00.123456+05:00")
            assert listing.status_code == 200
            assert all(item["original_created_at"] is None for item in listing.json()["items"])
            assert cleaned == 1
            assert [row["moved_to_dlq_at"] for row in remaining] == list(values)
